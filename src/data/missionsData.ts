const LABELS: Array<DecisionOption['id']> = ['A', 'B', 'C', 'D'];
const TARGET_SLOTS = [0, 3, 1, 2, 3, 0, 2, 1, 0, 2, 3, 1];

function rebalanceOptions(options: DecisionOption[], challengeIndex: number): DecisionOption[] {
  const targetSlot = TARGET_SLOTS[challengeIndex % TARGET_SLOTS.length];
  const optIdx = options.findIndex((o) => o.tier === 'optimal');
  if (optIdx === -1 || options.length !== 4) return options;

  const shift = (targetSlot - optIdx + 4) % 4;
  return options.map((_, i) => {
    const src = options[(i - shift + 4) % 4];
    return {
      ...src,
      id: LABELS[i],
    };
  });
}

let globalChallengeCounter = 0;

export const MISSIONS: MissionDefinition[] = RAW_MISSIONS.map((mission) => ({
  ...mission,
  challenges: mission.challenges.map((ch) => {
    const rebalanced = rebalanceOptions(ch.options, globalChallengeCounter++);
    return {
      ...ch,
      options: rebalanced,
    };
  }),
}));

export const RANDOM_EVENTS: RandomEventItem[] = RAW_RANDOM_EVENTS.map((ev, idx) => ({
  ...ev,
  options: rebalanceOptions(ev.options, idx + 1),
}));

